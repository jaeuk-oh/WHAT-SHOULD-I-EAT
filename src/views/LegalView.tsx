function Document({ title, sections }: { title: string; sections: Section[] }) {
  return (
    <div className="flex-1 flex flex-col min-h-screen bg-surface">
      <div className="w-full max-w-md mx-auto bg-surface min-h-screen">
        <AppHeader title={title} />
        <main className="px-5 py-4 pb-16 space-y-7">
          {sections.map((section) => (
            <section key={section.heading} className="space-y-2">
              <h2 className="text-base font-bold text-on-surface">{section.heading}</h2>
              {section.body.map((block, idx) =>
                Array.isArray(block) ? (
                  <ul key={idx} className="space-y-1.5 pl-1">
                    {block.map((line, i) => (
                      <li key={i} className="text-sm text-on-surface-variant leading-relaxed flex gap-2">
                        <span aria-hidden className="text-outline shrink-0">·</span>
                        <span>{line}</span>
                      </li>
                    ))}
                  </ul>
                ) : (
                  <p key={idx} className="text-sm text-on-surface-variant leading-relaxed">{block}</p>
                ),
              )}
            </section>
          ))}
        </main>
      </div>
    </div>
  );
}

